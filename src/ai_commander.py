"""
ai_commander.py — Real-Time DeepSeek AI Swarm Tactical Commander

Provides asynchronous, non-blocking tactical evaluation and multi-agent coordination
powered by the DeepSeek LLM (deepseek-v4-flash / deepseek-v4-pro).

Key Capabilities:
- Asynchronous Non-Blocking Loop: Never stalls the 100 Hz MuJoCo simulation or 60 Hz telemetry.
- Chain-of-Thought Military Reasoning: Captures raw reasoning tokens for real-time HUD streaming.
- Structured Tactical Directives: Dynamic strategic postures, priority targets, and enclosure angles.
- Human-in-the-Loop Operator Uplink: Direct natural language orders from the visualizer console.
"""

